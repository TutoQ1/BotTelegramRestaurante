-- ============================================================================
--  BotTelegramRestaurante - Esquema de base de datos (PostgreSQL 12+)
--  Ejecutar una sola vez. Es idempotente: se puede volver a ejecutar sin daño.
--
--  Convención de fechas: todas las columnas de fecha son 'timestamp' SIN zona
--  horaria y guardan la hora local del restaurante. La aplicación envía
--  DateTime.Now y Npgsql lo escribe con Kind=Unspecified. No cambiar a
--  'timestamptz' sin revisar también el código (ver db/README.md).
--
--  La base NO usa now()/localtimestamp para los datos del negocio: el servidor
--  puede estar en otra zona (por ejemplo UTC en la nube) y adelantaría o
--  atrasaría los avisos. Por eso esas columnas no tienen valor por defecto y
--  todos los tiempos los envía la aplicación.
-- ============================================================================

begin;

-- ---------------------------------------------------------------------------
-- Clientes: cada chat de Telegram que escribió al bot.
-- ---------------------------------------------------------------------------
create table if not exists clientes (
    chat_id        bigint      primary key,
    nombre         text        not null,
    creado_en      timestamp   not null,
    actualizado_en timestamp
);

comment on table  clientes            is 'Clientes de Telegram que han hablado con el bot.';
comment on column clientes.chat_id    is 'Identificador de chat de Telegram (puede ser negativo en grupos).';

-- ---------------------------------------------------------------------------
-- Platos: el menú. La carta se administra aquí, sin recompilar la aplicación.
-- ---------------------------------------------------------------------------
create table if not exists platos (
    opcion  text    primary key,
    nombre  text    not null unique,
    minutos integer not null check (minutos > 0),
    activo  boolean not null default true,
    orden   integer not null default 0
);

comment on table  platos        is 'Menú del restaurante. La opción es la letra que responde el cliente.';
comment on column platos.activo is 'false = el plato ya no se ofrece, pero se conserva por el historial.';

-- ---------------------------------------------------------------------------
-- Pedidos
--   estado (columna generada):
--     cancelado      -> cancelado_en no es null
--     listo          -> notificado_en no es null
--     en_preparacion -> resto
--   cliente_nombre y plato_nombre son copias del momento del pedido: si mañana
--   cambia el nombre de un plato, el historial no se altera.
-- ---------------------------------------------------------------------------
create table if not exists pedidos (
    id             bigint    generated by default as identity primary key,
    chat_id        bigint    not null references clientes (chat_id),
    cliente_nombre text      not null,
    opcion         text      not null references platos (opcion),
    plato_nombre   text      not null,
    minutos        integer   not null check (minutos > 0),
    hora_pedido    timestamp not null,
    hora_listo     timestamp not null,
    notificado_en  timestamp,
    cancelado_en   timestamp,
    estado         text      generated always as (
                                 case
                                     when cancelado_en  is not null then 'cancelado'
                                     when notificado_en is not null then 'listo'
                                     else 'en_preparacion'
                                 end
                             ) stored,
    constraint pedidos_no_doble_estado
        check (not (notificado_en is not null and cancelado_en is not null))
);

comment on table  pedidos        is 'Pedidos del bot. Nunca se borran: se marcan como listos o cancelados.';
comment on column pedidos.estado is 'Columna generada: en_preparacion | listo | cancelado.';

-- Panel: pendientes primero, por hora de entrega.
create index if not exists ix_pedidos_por_avisar
    on pedidos (hora_listo)
    where notificado_en is null and cancelado_en is null;

-- Comando /estado: pedidos pendientes de un chat.
create index if not exists ix_pedidos_pendientes_chat
    on pedidos (chat_id)
    where notificado_en is null and cancelado_en is null;

-- Historial: orden descendente por fecha.
create index if not exists ix_pedidos_historial
    on pedidos (hora_pedido desc);

-- ---------------------------------------------------------------------------
-- Cola de notificaciones: si Telegram falla, el aviso no se pierde.
--   estado: pendiente -> enviada | fallida | omitida
--   intentos + proximo_intento_en implementan el reintento con espera creciente.
--   El índice único (pedido_id, tipo) hace que encolar dos veces sea inocuo.
-- ---------------------------------------------------------------------------
create table if not exists notificaciones (
    id                 bigint    generated always as identity primary key,
    pedido_id          bigint    not null references pedidos (id) on delete cascade,
    tipo               text      not null check (tipo in ('pedido_listo', 'pedido_cancelado')),
    chat_id            bigint    not null,
    texto              text      not null,
    estado             text      not null default 'pendiente'
                                 check (estado in ('pendiente', 'enviada', 'fallida', 'omitida')),
    intentos           integer   not null default 0 check (intentos >= 0),
    ultimo_error       text,
    proximo_intento_en timestamp not null,
    creado_en          timestamp not null,
    enviado_en         timestamp
);

comment on table notificaciones is 'Bandeja de salida del bot: avisos pendientes de enviar por Telegram.';

create unique index if not exists ux_notificaciones_pedido_tipo
    on notificaciones (pedido_id, tipo);

create index if not exists ix_notificaciones_pendientes
    on notificaciones (proximo_intento_en)
    where estado = 'pendiente';

-- ---------------------------------------------------------------------------
-- Índice de búsqueda por nombre para consultas manuales (opcional).
-- Si el usuario de la base no puede crear extensiones, se avisa y se continúa.
-- ---------------------------------------------------------------------------
do $$
begin
    begin
        create extension if not exists pg_trgm;
        create index if not exists ix_pedidos_cliente_trgm
            on pedidos using gin (cliente_nombre gin_trgm_ops);
    exception
        when others then
            raise notice 'Aviso: no se pudo crear el índice pg_trgm (%). No es necesario para el bot.', sqlerrm;
    end;
end
$$;

commit;
